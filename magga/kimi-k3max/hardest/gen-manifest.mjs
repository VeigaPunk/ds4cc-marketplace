#!/usr/bin/env node
/* hardest/gen-manifest.mjs — regenerate manifest.js from levels/*.js (sorted).
 * Run after adding/removing a level file. Lanes never edit manifest.js. */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));
const files = readdirSync(join(DIR, 'levels')).filter(f => f.endsWith('.js')).sort();
const body = `/* GENERATED by gen-manifest.mjs — do not edit by hand. */
globalThis.HARDEST_MANIFEST = ${JSON.stringify(files)};
`;
writeFileSync(join(DIR, 'manifest.js'), body);
console.log(`manifest.js: ${files.length} levels`);
